/**
 * Regenerate stage — LLM-driven, template-bounded, clean-room.
 *
 * The model writes idiomatic code FROM THE SPEC ONLY. It never sees
 * minified bundle text: buildRegenPrompt's input type is the validated
 * UnvibeSpec, and a runtime assertion rejects bundle-shaped payloads.
 * All scaffolding (project layout, configs, Dockerfile, compose) comes
 * from @tamtunnel/unvibe-templates — the model NEVER generates scaffolding.
 */
import {
  buildRegenPrompt, scanOutputForBundleLeak, PROMPT_PACK_VERSION,
} from './prompts.js';
import { routeToPageFile } from './route-naming.js';
import type { LlmClient } from './llm.js';
import type { UnvibeSpec } from './spec.js';

export interface RegenerateOptions {
  spec: UnvibeSpec;
  llm: LlmClient;
  /** Deterministic scaffold files (from @tamtunnel/unvibe-templates). Never from the model. */
  scaffoldFiles: Record<string, string>;
  /**
   * Raw bundle text, used ONLY for the post-hoc verbatim-leak scan.
   * It is never included in any LLM prompt.
   */
  bundleTextForLeakScan?: string;
  onProgress?: (msg: string) => void;
}

export interface RegenerateResult {
  /** All output files: scaffold + generated, keyed by repo-relative path. */
  files: Record<string, string>;
  promptsVersion: string;
  /** Files generated by the model (vs. deterministic scaffold). */
  generatedByModel: string[];
  /** Verbatim-leak scan findings (empty = clean). */
  leakFindings: { file: string; chunkLength: number }[];
  /** True when no bundle text was available so the leak scan could not run. */
  leakScanSkipped: boolean;
}

export { routeToPageFile } from './route-naming.js';

/**
 * Strip accidental markdown fences AND leading model preamble — the model is
 * told to output only file content, but be lenient: drop any leading prose
 * lines before the first code-looking line.
 */
function unfence(text: string): string {
  const t = text.trim();
  const m = t.match(/^```(?:tsx|ts|typescript|jsx)?\n([\s\S]*?)\n```$/);
  if (m) return m[1];
  const lines = t.split('\n');
  let start = 0;
  if (/^```/.test(lines[0] ?? '')) start = 1; // unclosed fence: drop the fence line
  const codeLine =
    /^\s*(import|export|declare|const|let|var|function|class|interface|type|enum|\/\*|\/\/|@|<|['"])/;
  while (start < lines.length && !codeLine.test(lines[start])) start++;
  return lines.slice(start).join('\n').trim();
}

export async function regenerateFromSpec(opts: RegenerateOptions): Promise<RegenerateResult> {
  const log = opts.onProgress ?? (() => {});
  const files: Record<string, string> = { ...opts.scaffoldFiles };
  const generatedByModel: string[] = [];

  const generate = async (
    targetFile: string,
    kind: 'route-page' | 'api-client' | 'entity-types',
    routePath?: string,
  ): Promise<void> => {
    log(`regenerate: ${targetFile} (via ${opts.llm.provider}/${opts.llm.model})`);
    const messages = buildRegenPrompt({ spec: opts.spec, targetFile, kind, routePath });
    const raw = await opts.llm.complete(messages);
    files[targetFile] = unfence(raw);
    generatedByModel.push(targetFile);
  };

  // One page component per route.
  for (const route of opts.spec.routes) {
    await generate(routeToPageFile(route.path), 'route-page', route.path);
  }
  // Typed API client (only if endpoints were observed).
  if (opts.spec.endpoints.length > 0) {
    await generate('src/lib/api.ts', 'api-client');
  }
  // Entity types (only if a data model was inferred).
  if (opts.spec.entities.length > 0) {
    await generate('src/types.ts', 'entity-types');
  }

  // Post-hoc clean-room scan. Bundle text is used ONLY here — never in prompts.
  // This is a tripwire, not a guarantee: it catches verbatim copies, not
  // paraphrases. A skipped scan (no bundle text) is reported, never silent.
  let leakFindings: { file: string; chunkLength: number }[] = [];
  const leakScanSkipped = !opts.bundleTextForLeakScan;
  if (opts.bundleTextForLeakScan) {
    const generated: Record<string, string> = {};
    for (const f of generatedByModel) generated[f] = files[f];
    leakFindings = scanOutputForBundleLeak(generated, opts.bundleTextForLeakScan);
    if (leakFindings.length > 0) {
      log(`regenerate: WARN ${leakFindings.length} verbatim-leak finding(s) — review before shipping`);
    }
  }

  return { files, promptsVersion: PROMPT_PACK_VERSION, generatedByModel, leakFindings, leakScanSkipped };
}
