/**
 * Deterministic output scaffolds.
 *
 * Everything in this module is hand-written template code rendered from the
 * spec's structural facts (route paths, entity names, endpoint lists). The
 * model NEVER generates scaffolding — it only fills in page components,
 * the API client, and entity types from behavioral spec data.
 */
import type { UnvibeSpec, SpecEntity } from '@tamtunnel/unvibe-core';
import { routeToComponentName as canonicalComponentName, routeToImportSpecifier as canonicalImportSpecifier } from '@tamtunnel/unvibe-core';

const SQL_TYPES: Record<string, string> = {
  string: 'text',
  number: 'numeric',
  boolean: 'boolean',
  date: 'timestamptz',
  json: 'jsonb',
  uuid: 'uuid',
};

const DRIZZLE_TYPES: Record<string, string> = {
  string: 'text',
  number: 'numeric',
  boolean: 'boolean',
  date: 'timestamp',
  json: 'jsonb',
  uuid: 'uuid',
};

// Route naming is canonical in @tamtunnel/unvibe-core (route-naming.ts) so the
// scaffold, the regenerate prompt, and the verify gate all agree.
const routeComponentName = canonicalComponentName;
// routeFile is relative to src/ (App.tsx lives at src/App.tsx), extensionless.
const routeFile = (path: string): string => canonicalImportSpecifier(path);

export function renderDrizzleSchema(entities: SpecEntity[]): string {
  const imports = new Set<string>(['pgTable']);
  for (const e of entities) for (const f of e.fields) {
    const t = DRIZZLE_TYPES[f.type] ?? 'text';
    imports.add(t);
    if (f.name === 'id') imports.add('uuid');
  }
  const tables = entities.map((e) => {
    const cols = e.fields.map((f) => {
      const t = DRIZZLE_TYPES[f.type] ?? 'text';
      const colFn = f.name === 'id' && f.type === 'uuid'
        ? `uuid("id").primaryKey().defaultRandom()`
        : `${t}("${f.name}")${f.nullable ? '' : '.notNull()'}`;
      return `  ${f.name}: ${colFn},`;
    }).join('\n');
    return `export const ${e.tableName} = pgTable("${e.tableName}", {\n${cols}\n});`;
  }).join('\n\n');
  return `// Generated by Unvibe from observed payload shapes.\n// Tables are created WITHOUT RLS policies — see BACKEND-GAPS.md.\nimport { ${[...imports].join(', ')} } from "drizzle-orm/pg-core";\n\n${tables || '// no entities were observed in capture'}\n`;
}

export function renderSqlMigration(entities: SpecEntity[]): string {
  const tables = entities.map((e) => {
    const cols = e.fields.map((f) => {
      const t = SQL_TYPES[f.type] ?? 'text';
      const pk = f.name === 'id' ? ' primary key' : '';
      const nn = !f.nullable && f.name !== 'id' ? ' not null' : '';
      return `  "${f.name}" ${t}${pk}${nn}`;
    }).join(',\n');
    return `-- Entity: ${e.name} (evidence: ${(e.evidence ?? []).join('; ') || 'observed payload'})\n` +
      `-- NOTE: no RLS policies — add them manually, see BACKEND-GAPS.md\n` +
      `create table if not exists "${e.tableName}" (\n${cols}\n);`;
  }).join('\n\n');
  return `-- Unvibe migration 0001 — generated from observed payload shapes.\n-- RLS is NOT enabled here by design: add policies manually (BACKEND-GAPS.md).\n\n${tables || '-- no entities were observed in capture'}\n`;
}

export function renderAppTsx(spec: UnvibeSpec): string {
  const imports = spec.routes.map((r) => `import ${routeComponentName(r.path)} from "${routeFile(r.path)}";`).join('\n');
  const routeEls = spec.routes.map((r) => `        <Route path="${r.path}" element={<${routeComponentName(r.path)} />} />`).join('\n');
  return `import { BrowserRouter, Routes, Route, Link } from "react-router-dom";
${imports}

export default function App() {
  return (
    <BrowserRouter>
      <nav className="app-nav">
${spec.routes.map((r) => `        <Link to="${r.path}">${r.title ?? r.path}</Link>`).join('\n')}
      </nav>
      <Routes>
${routeEls}
      </Routes>
    </BrowserRouter>
  );
}
`;
}

const HTTP_TS = `// Minimal typed fetch helper used by the generated API client.
export async function apiRequest(
  method: string,
  urlPattern: string,
  params: Record<string, string | number> = {},
  body?: unknown,
): Promise<unknown> {
  let url = urlPattern;
  for (const [k, v] of Object.entries(params)) url = url.replace(\`:\${k}\`, encodeURIComponent(String(v)));
  const base = import.meta.env.VITE_API_BASE_URL ?? "";
  const res = await fetch(base + url, {
    method,
    headers: { "content-type": "application/json" },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  if (!res.ok) throw new Error(\`API \${method} \${url} failed: \${res.status}\`);
  const ct = res.headers.get("content-type") ?? "";
  return ct.includes("json") ? res.json() : res.text();
}
`;

function renderSupabaseAdapter(spec: UnvibeSpec): string {
  const provider = spec.auth.provider;
  if (provider === 'supabase') {
    return `// Auth adapter — Supabase. Points at YOUR instance via env vars.
// Migration runbook: docs/auth-migration-runbook.md
import { createClient } from "@supabase/supabase-js";

const url = import.meta.env.VITE_SUPABASE_URL;
const anonKey = import.meta.env.VITE_SUPABASE_ANON_KEY;
if (!url || !anonKey) {
  console.warn("Supabase env vars missing — set VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY");
}

export const supabase = createClient(url ?? "", anonKey ?? "");
`;
  }
  return `// Auth adapter — detected provider: ${provider}.
// No provider-specific client was generated. See docs/auth-migration-runbook.md
// for the manual migration steps, and BACKEND-GAPS.md for what was not recovered.
export const authProvider = "${provider}" as const;
`;
}

