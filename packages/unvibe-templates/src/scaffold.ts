/**
 * Render the full deterministic scaffold for a spec.
 * Returns repo-relative path → file content.
 */
export function renderScaffold(spec: UnvibeSpec): Record<string, string> {
  return {
    'package.json': renderPackageJson(spec),
    'vite.config.ts': VITE_CONFIG,
    'tsconfig.json': TSCONFIG,
    'tailwind.config.js': TAILWIND_CONFIG,
    'postcss.config.js': POSTCSS_CONFIG,
    'index.html': INDEX_HTML,
    'src/main.tsx': MAIN_TSX,
    'src/App.tsx': renderAppTsx(spec),
    'src/index.css': INDEX_CSS,
    'src/lib/http.ts': HTTP_TS,
    'src/lib/auth.ts': renderSupabaseAdapter(spec),
    'src/components/ui/button.tsx': UI_BUTTON,
    'src/components/ui/card.tsx': UI_CARD,
    'src/components/ui/input.tsx': UI_INPUT,
    'drizzle/schema.ts': renderDrizzleSchema(spec.entities),
    'drizzle.config.ts': `import { defineConfig } from "drizzle-kit";\nexport default defineConfig({ schema: "./drizzle/schema.ts", out: "./supabase/migrations", dialect: "postgresql" });\n`,
    'supabase/migrations/0001_unvibe.sql': renderSqlMigration(spec.entities),
    'docker-compose.yml': renderDockerCompose(),
    Dockerfile: DOCKERFILE,
    'nginx.conf': NGINX_CONF,
    '.env.example': ENV_EXAMPLE,
    '.gitignore': 'node_modules/\ndist/\n.env\n',
    'docs/auth-migration-runbook.md': renderAuthRunbook(spec),
    'README.md': renderOutputReadme(spec),
    'unvibe-spec.json': JSON.stringify(spec, null, 2) + '\n',
  };
}
